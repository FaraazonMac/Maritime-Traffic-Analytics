"""Writes FINDINGS.md: the written analysis. Every number is computed from the data, nothing is typed in by hand."""
import numpy as np
import pandas as pd

from .config import DARK_WINDOW_MINUTES


def _n(x):
    return f"{int(round(float(x))):,}"


def _rng(lo, hi, nd=0):
    return f"{lo:,.{nd}f} to {hi:,.{nd}f}"


def _md_table(df, cols=None, fmt=None):
    cols = cols or list(df.columns)
    fmt = fmt or {}
    out = ["| " + " | ".join(cols) + " |", "|" + "|".join(["---"] * len(cols)) + "|"]
    for _, r in df.iterrows():
        cells = []
        for c in cols:
            v = r[c]
            cells.append("" if pd.isna(v) else (fmt[c](v) if c in fmt else str(v)))
        out.append("| " + " | ".join(cells) + " |")
    return "\n".join(out)


def _edge_sentence(de):
    """Edge vs interior silent-ship rate, with an approximate 95% interval and a plain verdict."""
    if not {"near edge of tracked area", "interior"} <= set(de.index):
        return None
    e, i = de.loc["near edge of tracked area"], de.loc["interior"]
    n1, n2 = float(e["ships"]), float(i["ships"])
    if n1 == 0 or n2 == 0:
        return None
    if float(e["dark"]) + float(i["dark"]) == 0:
        return "no ships in this window were flagged, so there is nothing to compare."
    p1, p2 = float(e["dark"]) / n1, float(i["dark"]) / n2
    se = (p1 * (1 - p1) / n1 + p2 * (1 - p2) / n2) ** 0.5
    verdict = ("no statistically clear difference" if abs(p1 - p2) < 1.96 * se else
               ("higher near the edge" if p1 > p2 else "higher in the interior"))
    return f"{100 * p1:.2f}% near the edge vs {100 * p2:.2f}% in the interior ({100 * (p1 - p2):+.2f} points, approx. 95% interval +/-{196 * se:.2f}): {verdict}."


def build(path, m, est, df, hubs, stamp, region, assump, tr=None, weather=None, sql_checks=None, filter_note=None):
    k = m["kpis"]
    ht = m["hub_table"]
    L = []
    add = L.append

    add(f"# Maritime Traffic Analytics: {region}\n")
    add(f"_Snapshot: {k['snapshot_utc']} UTC · {_n(k['total_ships'])} current ships · generated by `run_all.py`. " + (f"**Filtered to vessel types: {filter_note}.** " if filter_note else "") +
        "Every number below is computed from the data; interpretation lines are marked and should be reviewed by the analyst._\n")

    if k["pct_type_unknown"] >= 20:
        add(f"> **Caution:** {k['pct_type_unknown']}% of ships have no vessel type yet. Type, IMO and length arrive minutes to hours after the backend starts, "
            "so type, IMO, size and destination shares in this run are understated, and ships flagged silent are undercounted. "
            "Re-run after the backend has been up for several hours before quoting them.\n")
    # ------------------------------------------------------------ executive summary
    add("## Executive summary\n")
    add(f"- **Fleet.** {_n(k['total_ships'])} ships were current (heard from in the last 15 minutes): {k['pct_moving']}% under way (speed 0.5 kn or more), {k['pct_idle']}% idle (stationary although the status says under way), {k['pct_at_anchor']}% at anchor, {k['pct_at_berth']}% moored. "
        f"{_n(k['ships_near_hubs'])} were inside the radius of one of {len(hubs)} port hubs. "
        f"{_n(k['total_ships_incl_silent'] - k['total_ships'])} further ships had gone silent and are used only for the dark-fleet analysis.")
    top = ht.iloc[0]
    reds = ht[ht["level_waiting"] == "red"]["hub"].tolist()
    if top["at_anchor"] > 0:
        add(f"- **Congestion.** {top['hub']} had the most ships waiting at anchor ({_n(top['at_anchor'])}, {top['pct_at_anchor']}% of ships in its radius). "
            "Top 3 by waiting ships: " + ", ".join(f"{r['hub']} ({_n(r['at_anchor'])})" for _, r in ht.head(3).iterrows()) + ".")
    else:
        add("- **Congestion.** No ships were waiting at anchor inside any hub radius in this snapshot.")
    so = m["speed_overall"]
    if {"near a hub", "open water"} <= set(so.index):
        near_s, open_s = so.loc["near a hub", "mean"], so.loc["open water", "mean"]
        add(f"- **Speed.** Ships under way average {near_s:.1f} kn near hubs and {open_s:.1f} kn in open water ({near_s - open_s:+.1f} kn difference).")
    de = m["dark_edge"].set_index("location")
    dp = m.get("dark_profile")
    if dp:
        edge_s = _edge_sentence(de)
        add(f"- **Silent-ship flags (the app's 'dark fleet').** {k['pct_dark']}% of the {_n(k['ships_in_dark_window'])} ships heard from in the last hour have been silent for 20+ minutes. "
            f"{dp['pct_stationary']}% of them were stationary (moored, at anchor or idle) when last heard and {dp['pct_type_unknown_flagged']}% have no vessel type "
            f"(against {dp['pct_type_unknown_current']}% of current ships), so most gaps look like harbour traffic and reception gaps, not deliberate shutdowns."
            + (f" Edge vs interior: {edge_s}" if edge_s else ""))
    else:
        add(f"- **Silent-ship flags.** No ships heard from in the last hour were flagged as silent.")
    add(f"- **Data quality.** Only {k['pct_valid_imo']}% of ships carry a valid IMO number and {k['pct_type_unknown']}% have no vessel type. "
        f"Cleaning free-text destinations raised the share resolved to a port from {k['pct_dest_app_matched']}% to {k['pct_dest_resolved']}%.")
    tot = est[est["size_class"] == "Total"].iloc[0]
    if tot["ships_waiting"] > 0:
        add(f"- **Estimated cost of waiting (estimate, not measured).** Ships at anchor near hubs burn roughly {_rng(tot['fuel_t_low'], tot['fuel_t_high'])} t of fuel "
            f"and cost about ${_rng(tot['cost_usd_low'] / 1e6, tot['cost_usd_high'] / 1e6, 1)} million per day (central case ${tot['cost_usd_central'] / 1e6:.1f} million).\n")
    else:
        add("- **Estimated cost of waiting.** Not computed: no ships were waiting at anchor near a hub.\n")

    # ------------------------------------------------------------ findings
    add("## Findings\n")
    ft = m["fleet_by_type"]
    ft_known = ft[ft["vessel_type"] != "unknown"]
    add("### 1. Fleet composition\n")
    add("![Fleet by vessel type](charts/01_fleet_by_type.png)\n")
    if len(ft_known):
        t0 = ft_known.iloc[0]
        add(f"Among ships with a known type, **{t0['vessel_type']}** is the largest group ({_n(t0['ships'])} ships, {t0['share_pct']}% of the fleet). "
            f"{k['pct_type_unknown']}% of ships have no type at all, so type shares describe the typed ships only.")
    fl = m["flags_top"]
    if len(fl):
        add(f"The most common flag is **{fl.iloc[0]['flag']}** ({fl.iloc[0]['share_pct']}%). The top 3 flags together cover {fl.head(3)['share_pct'].sum():.1f}% of ships.\n")

    seg = m["segments"]
    add("**Who is in the data?** The feed mixes seagoing and local traffic (tugs, ferries, pleasure craft, inland barges), and each segment behaves differently, "
        "so one fleet-wide average would hide most of the story:\n")
    add("![By segment](charts/13_segments.png)\n")
    add(_md_table(seg, ["segment", "ships", "share_pct", "pct_under_way", "pct_idle", "pct_at_berth", "pct_at_anchor", "waiting_near_hubs", "avg_speed_under_way_kn"]) + "\n")

    add("### 2. Congestion hotspots\n")
    add("![Hub congestion](charts/04_hub_congestion_levels.png)\n")
    add(_md_table(ht.head(8), ["hub", "zone", "ships_in_radius", "at_anchor", "idle", "waiting_broad", "pct_at_anchor", "level_waiting"]) + "\n")
    sens = m.get("sensitivity")
    if sens:
        add(f"**Sensitivity to the definition of waiting.** Strict = anchored at sea; broad = anchored plus idle (stationary although the status says under way). "
            f"{sens['top5_overlap']} of the top 5 hubs are the same under both definitions (rank correlation {sens['rank_correlation']}). "
            + ("The ranking is robust to the definition." if sens["top5_overlap"] >= 4 and sens["rank_correlation"] >= 0.8 else
               ("The top of the ranking is fairly stable, but the full ranking shifts with the definition, so quote the top hubs rather than exact positions." if sens["top5_overlap"] >= 3 else
                "The ranking depends on the definition, so treat individual hub ranks with caution.")) + "\n")

    zt = m["zone_table"]
    if len(zt) and zt["at_anchor"].sum() > 0:
        add(f"Across sub-zones, **{zt.iloc[0]['zone']}** has the most ships at anchor ({_n(zt.iloc[0]['at_anchor'])}), "
            f"while **{zt.sort_values('pct_at_anchor', ascending=False).iloc[0]['zone']}** has the highest share of ships at anchor ({zt['pct_at_anchor'].max()}%).")
    add("_Interpretation (review): levels are relative to the other hubs, from a single moment. A red hub is busy compared with the others today; "
        "this snapshot cannot say whether that is normal for that hub. That needs the time analysis._\n")

    add("### 3. Do ships slow down near hubs?\n")
    add("![Speed near hubs vs open water](charts/05_speed_near_vs_open.png)\n")
    sz = m["speed_zone"]
    if {"near a hub", "open water"} <= set(so.index):
        diff = so.loc["near a hub", "mean"] - so.loc["open water", "mean"]
        verdict = ("no clear difference (under 0.5 kn)" if abs(diff) < 0.5 else
                   ("ships are slower near hubs" if diff < 0 else "ships are faster near hubs"))
        add(f"Overall: {verdict} ({so.loc['near a hub', 'mean']:.1f} kn near hubs, {so.loc['open water', 'mean']:.1f} kn in open water; "
            f"{_n(so.loc['near a hub', 'count'])} and {_n(so.loc['open water', 'count'])} moving ships).")
    if len(sz):
        piv = sz.pivot(index="vessel_type", columns="location", values="avg_speed_kn").dropna()
        if len(piv) and {"near a hub", "open water"} <= set(piv.columns):
            piv["diff"] = piv["near a hub"] - piv["open water"]
            low = piv["diff"].idxmin()
            add(f" The largest slowdown among the main types is for **{low}** ({piv.loc[low, 'diff']:+.1f} kn).")
    add("\n_Interpretation (review): a speed gap near hubs would be consistent with queuing and manoeuvring, but moving-ship speed near a port also reflects "
        "pilotage rules and speed limits, so treat this as a signal, not proof of congestion._\n")

    add("### 4. Voyages and destinations\n")
    add("![Top routes](charts/10_top_routes.png)\n")
    rt = m["routes"]
    if len(rt):
        add(f"{_n(k['ships_with_departure'])} ships have a detected departure port. The most common voyage observed is "
            f"**{rt.iloc[0]['departure_port']} → {rt.iloc[0]['destination']}** ({_n(rt.iloc[0]['ships'])} ships).")
    else:
        add("No ships have both a detected departure and a usable destination yet. Departures are only detected while the backend is running.")
    add("![Destination quality](charts/08_destination_quality.png)\n")
    dq = m["dest_quality"].set_index("category")["share_pct"]
    add(f"Captains type destinations by hand: {dq.get('missing', 0)}% are blank and {dq.get('junk', 0)}% are placeholders such as 'FOR ORDERS'. "
        f"{dq.get('locode', 0)}% are port codes for a known hub and {dq.get('hub_name', 0)}% name a known hub, which cleaning maps to a real port.\n")

    add("### 5. Silent ships (the 'dark-fleet' flag)\n")
    add("![Silent-ship flags: edge vs interior](charts/06_dark_edge_vs_interior.png)\n")
    add(f"Only ships heard from in the last {DARK_WINDOW_MINUTES} minutes are compared. The backend keeps silent ships longer in the interior than near the edge of the tracked area, "
        "so including older ships would manufacture a difference between the two.\n")
    edge_s = _edge_sentence(de)
    if edge_s:
        add(f"Edge versus interior: {edge_s}\n")
    if dp:
        add(f"Of the {_n(dp['flagged'])} flagged ships, **{dp['pct_stationary']}%** were stationary when last heard ({dp['pct_under_way']}% were under way), "
            f"{dp['pct_in_hub']}% were inside a hub radius, the median silence is {dp['median_silent_min']} minutes, and **{dp['pct_type_unknown_flagged']}%** have no vessel type "
            f"(current ships: {dp['pct_type_unknown_current']}%). Ships with no type are ones heard only a few times, so many flags are simply ships at the fringe of reception.\n")
    add("_Interpretation (review): the flag means 20+ minutes without a message. On this evidence it measures signal gaps and powered-down harbour craft, not suspicious behaviour, "
        "so call it a signal-gap or silent-ship indicator; it cannot separate a deliberate shutdown from a coverage gap._\n")

    add("### 6. Data quality\n")
    add("![Data completeness](charts/07_data_quality.png)\n")
    comp = m["completeness"].sort_values("pct_complete")
    worst = comp.head(3)
    incons = k["stationary_but_moving"] + k["moving_but_anchored"]
    tail = (f"{k['stationary_but_moving']} ships ({k['pct_idle']}% of the fleet) have a status that says under way but are stationary, and {k['moving_but_anchored']} report anchored or moored while moving fast. "
            "Status is typed by hand and often not updated, so this analysis classifies ships by speed as well as status." if incons else
            "No ships had a navigation status that contradicted their speed.")
    add("The least complete fields: " + "; ".join(f"**{r['field']}** ({r['pct_complete']}%)" for _, r in worst.iterrows()) + ". " + tail + "\n")

    add("### 7. Estimated fuel, CO2 and cost of ships waiting at anchor (ESTIMATE)\n")
    if tot["ships_waiting"] > 0:
        add("![Estimates](charts/12_estimates.png)\n")
        add(f"{_n(tot['ships_waiting'])} ships were at anchor inside a hub radius. Using the assumptions in the appendix, they burn about "
            f"**{_rng(tot['fuel_t_low'], tot['fuel_t_high'])} t of fuel**, emit **{_rng(tot['co2_t_low'], tot['co2_t_high'])} t of CO2** and cost **${_rng(tot['cost_usd_low'] / 1e6, tot['cost_usd_high'] / 1e6, 1)} million** per day "
            f"(low to high; central {tot['fuel_t_central']:,.0f} t, {tot['co2_t_central']:,.0f} t, ${tot['cost_usd_central'] / 1e6:.1f} million).\n")
        unk = est[est["size_class"] == "unknown size"].iloc[0]["ships_waiting"]
        add(f"**How to read this honestly:** it is the cost of ships idling near a hub on a typical day, an upper bound for congestion-attributable cost because some waiting is normal. "
            f"{_n(unk)} of the waiting ships have no length in the data and use medium-ship assumptions. AIS has no fuel, operator or cargo data, so no company-level loss can be computed.\n")
    else:
        add("No ships were waiting at anchor inside a hub radius, so no estimate was computed.\n")

    # ------------------------------------------------------------ time analysis
    add("## Time analysis (v2)\n")
    if tr is None:
        add("Not available yet. Run `python analysis/collector.py` for several weeks, then re-run `run_all.py`. "
            "Daily traffic levels need 3+ days of data, weekday patterns 14+, weekly summaries 14+ and monthly summaries 28+.\n")
    else:
        st = tr["status"]
        add(f"History: {st['polls']} polls over {st['days_seen']} days ({st['usable_days']} usable with at least half the expected polls), every {st['interval_min']:g} minutes, "
            f"{st['first']} to {st['last']}; {st['failed_polls']} failed polls; mean daily coverage {st['mean_coverage_pct']}%. Gaps are real: the laptop or backend was off.\n")
        d = tr["daily"]
        lv = d.dropna(subset=["congestion_level"])
        if len(lv):
            c = lv["congestion_level"].value_counts()
            add(f"Of {len(lv)} usable days: **{c.get('green', 0)} green**, **{c.get('yellow', 0)} yellow**, **{c.get('red', 0)} red** "
                "(levels are the lowest, middle and top third of this period's own daily congestion, not an external standard).\n")
            add("![Calendar](time/t2_calendar.png)\n")
        para = []
        if "hour_profile" in tr:
            h = tr["hour_profile"].sort_values("waiting", ascending=False).iloc[0]
            para.append(f"Ships waiting peak around **{int(h['hour']):02d}:00** local time (about {h['waiting']:.0f} ships on average).")
        if "weekday_profile" in tr:
            w = tr["weekday_profile"].sort_values("waiting", ascending=False).iloc[0]
            para.append(f"The busiest weekday is **{w['day']}** ({w['waiting']:.0f} ships waiting on average).")
        if para:
            add(" ".join(para) + "\n")
        if "type_queue" in tr:
            q = tr["type_queue"].iloc[0]
            add(f"**{q['vessel_type']}** ships make up {q['share_of_queue_pct']}% of the waiting queue but {q['share_of_fleet_pct']}% of the fleet "
                f"(queue-to-fleet ratio {q['queue_vs_fleet']}).\n")
        if "speed_by_level" in tr:
            sp = tr["speed_by_level"].set_index("congestion_level")["mean"]
            if {"green", "red"} <= set(sp.index):
                add(f"Average speed near hubs: {sp['green']:.2f} kn on green days vs {sp['red']:.2f} kn on red days.\n")
        if "excess" in tr:
            ex = tr["excess"]
            t = ex["table"].set_index("scenario")
            add(f"**Excess waiting over a green-day baseline (ESTIMATE).** Baseline: {ex['baseline_waiting_ships']} ships waiting on an average green day. "
                f"On {ex['days_counted']} yellow/red days the excess adds up to {ex['excess_ship_days']:,.0f} ship-days of waiting, about "
                f"{_rng(t.loc['low', 'fuel_t'], t.loc['high', 'fuel_t'])} t of fuel, {_rng(t.loc['low', 'co2_t'], t.loc['high', 'co2_t'])} t of CO2 and "
                f"${_rng(t.loc['low', 'cost_usd'] / 1e6, t.loc['high', 'cost_usd'] / 1e6, 1)} million (low to high). This is the defensible 'cost of congestion' figure, "
                "because it counts only waiting above normal.\n")
        if weather is not None:
            add("**Weather and waiting.** Spearman correlation between daily waiting ships and weather (permutation p-value):\n")
            add(_md_table(weather) + "\n")
        if tr["messages"]:
            add("_Not yet available:_ " + " ".join(tr["messages"]) + "\n")
        add("")

    # ------------------------------------------------------------ recommendations
    add("\n## Recommendations (draft: edit to your own judgement)\n")
    recs = []
    if reds:
        recs.append(f"Put {', '.join(reds[:3])} on a watch list and track their waiting ships hourly; they lead the congestion ranking in this snapshot.")
    if k["pct_valid_imo"] < 70:
        recs.append(f"Improve vessel identification: only {k['pct_valid_imo']}% of ships have a valid IMO, so many ships cannot be matched to registry data (size, owner, age).")
    if k["pct_dest_resolved"] < 80:
        recs.append("Normalise destination text at the source (UN/LOCODE parsing, as done here) before using it for voyage analysis.")
    if tr is None:
        recs.append("Keep the collector running for 4+ weeks to move from a snapshot to trends, weekly and monthly patterns, and a baseline for the cost of congestion.")
    recs.append("Add ship size (length and beam from AIS) to every record so fuel and cost estimates can be scaled by size class instead of an average.")
    for r in recs:
        add(f"- {r}")

    # ------------------------------------------------------------ method, limitations, assumptions
    add("\n## Method\n")
    add("1. **Source.** Live AIS positions and static data from AISStream, collected by the Maritime Globe backend (North Sea and English Channel box).")
    add("2. **Cleaning.** Every rule and the number of rows it touched:\n")
    add(_md_table(m["cleaning_log"]))
    add("\n3. **Hubs.** Each ship is assigned to the nearest port hub whose radius it is inside (`config/hubs.csv`); otherwise it counts as open water.")
    add("4. **Levels.** Hubs (or days) are split into thirds: lowest green, middle yellow, top red. Relative, not absolute.")
    add("5. **Cross-check.** The same headline numbers are computed twice, in pandas and in SQL (`sql/`), and compared." +
        (" Result: " + ", ".join(f"{n}: {'agree' if ok else 'DISAGREE'}" for n, ok in sql_checks) + "." if sql_checks else ""))
    add("6. **Estimates.** Fuel, CO2 and cost use the published ranges in `config/assumptions.csv`; low uses every low value together and high every high value.\n")
    add("## Limitations\n")
    for x in [
        "One region only (North Sea and English Channel). Findings do not generalise to other seas.",
        "Coverage comes from land-based AIS receivers, so open-sea traffic is under-represented; counts depend on receiver coverage and on when the backend was running.",
        "A single snapshot shows one moment. Trends, weekly and monthly patterns need the history collector.",
        "Navigation status is entered by the crew; 'at anchor' can be wrong or stale.",
        "Fuel, CO2 and cost are estimates from published assumptions, not measurements. No operator, cargo or schedule data exists in AIS, so no company-level loss can be calculated.",
        "Departure ports are detected only while the backend is running; ships that left earlier are unknown.",
    ]:
        add(f"- {x}")
    add("\n## Appendix: assumptions and sources\n")
    a = assump.copy()
    add(_md_table(a[["parameter", "size_class", "low", "central", "high", "unit"]]))
    add("\nSources:\n")
    for _, r in a.drop_duplicates("parameter").iterrows():
        add(f"- **{r['parameter']}**: {r['source']}")
    path.write_text("\n".join(L), encoding="utf-8")
    return path
